-- ─── Đơn hàng ────────────────────────────────────────────────
-- Mã đơn dạng #CB1234, không trùng
create or replace function public.generate_order_id()
returns text
language plpgsql
as $$
declare
  new_id text;
begin
  loop
    new_id := '#CB' || (1000 + floor(random() * 9000))::int;
    exit when not exists (select 1 from public.orders where id = new_id);
  end loop;
  return new_id;
end;
$$;

create table public.orders (
  id              text primary key,
  created_at      date not null default public.today_vn(),
  -- [{ "name": ..., "size": ..., "quantity": 1, "price": 350000 }, ...]
  items           jsonb not null,
  subtotal        int  not null check (subtotal >= 0),
  voucher_code    text,
  discount        int  not null default 0 check (discount >= 0),
  total           int  not null check (total >= 0),
  status          text not null default 'Chờ xử lý' check (status in ('Chờ xử lý', 'Đã giao', 'Đã hủy')),
  fulfillment     text not null check (fulfillment in ('delivery', 'pickup')),
  address         text,
  receive_date    date not null,
  receive_time    text not null,
  note            text,
  payment_method  text not null check (payment_method in ('cod', 'bank')),
  customer_name   text,
  customer_phone  text,
  customer_email  text,
  user_id         uuid references auth.users (id) on delete set null default auth.uid()
);
alter table public.orders alter column id set default public.generate_order_id();
create index orders_customer_email_idx on public.orders (lower(customer_email));

-- ─── Lịch sử điểm ────────────────────────────────────────────
create sequence public.point_code_seq;

create table public.point_logs (
  id        text primary key default 'P' || lpad(nextval('public.point_code_seq')::text, 3, '0'),
  email     text not null,
  date      date not null default public.today_vn(),
  title     text not null,
  points    int  not null check (points <> 0),
  kind      text not null check (kind in ('order', 'manual', 'redeem', 'initial')),
  order_id  text references public.orders (id) on delete set null,
  reason    text
);
create index point_logs_email_idx on public.point_logs (lower(email));
-- Mỗi đơn chỉ được cộng điểm 1 lần
create unique index point_logs_one_per_order on public.point_logs (order_id) where kind = 'order';

-- Quy tắc tích điểm: 1.000đ = 1 điểm
create or replace function public.points_for_order(p_total int)
returns int
language sql immutable
as $$ select floor(p_total / 1000.0)::int; $$;

