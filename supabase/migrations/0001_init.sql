-- Ngày hiện tại theo giờ Việt Nam (server Supabase chạy giờ UTC)
create or replace function public.today_vn()
returns date
language sql stable
as $$ select (now() at time zone 'Asia/Ho_Chi_Minh')::date; $$;

-- Lệnh đến từ website (khách vãng lai hoặc người đã đăng nhập)? Chạy trong SQL Editor thì trả về false.
create or replace function public.from_website()
returns boolean
language sql stable
as $$ select coalesce(auth.jwt() ->> 'role', '') in ('anon', 'authenticated'); $$;

-- ─── Hồ sơ người dùng đăng nhập (1-1 với auth.users) ─────────
create table public.profiles (
  id          uuid primary key references auth.users (id) on delete cascade,
  full_name   text not null default '',
  phone       text not null default '',
  role        text not null default 'customer' check (role in ('customer', 'admin')),
  created_at  timestamptz not null default now()
);

-- Kiểm tra người đang gọi có phải admin không (security definer để tránh vòng lặp RLS)
create or replace function public.is_admin()
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

-- Email của người đang đăng nhập (chữ thường), dùng để khớp đơn hàng / điểm theo email
create or replace function public.current_email()
returns text
language sql stable
as $$
  select lower(coalesce(auth.jwt() ->> 'email', ''));
$$;

-- ─── Khách hàng (khóa theo email, như dữ liệu mẫu) ───────────
create sequence public.customer_code_seq;

create table public.customers (
  id          text primary key default 'KH' || lpad(nextval('public.customer_code_seq')::text, 3, '0'),
  user_id     uuid unique references auth.users (id) on delete set null,
  full_name   text not null,
  email       text not null,
  phone       text not null default '',
  created_at  date not null default public.today_vn()
);
create unique index customers_email_key on public.customers (lower(email));

-- Tạo hồ sơ khách nếu email chưa có (dùng trong trigger, chạy với quyền hệ thống)
create or replace function public.ensure_customer(p_full_name text, p_email text, p_phone text, p_user_id uuid default null)
returns void
language plpgsql security definer set search_path = ''
as $$
begin
  if coalesce(trim(p_email), '') = '' then
    return;
  end if;
  insert into public.customers (full_name, email, phone, user_id)
  values (coalesce(nullif(trim(p_full_name), ''), trim(p_email)), trim(p_email), coalesce(trim(p_phone), ''), p_user_id)
  on conflict ((lower(email))) do update
    set user_id = coalesce(public.customers.user_id, excluded.user_id);
end;
$$;

-- Khi có người đăng ký tài khoản: tạo profile + hồ sơ khách
create or replace function public.handle_new_user()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, phone)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', ''), coalesce(new.raw_user_meta_data ->> 'phone', ''));

  perform public.ensure_customer(
    coalesce(new.raw_user_meta_data ->> 'full_name', split_part(new.email, '@', 1)),
    new.email,
    new.raw_user_meta_data ->> 'phone',
    new.id
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

