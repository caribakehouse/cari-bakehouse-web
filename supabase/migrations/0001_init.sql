-- profiles: tự xem/sửa hồ sơ của mình (không tự đổi role), admin xem tất cả
create policy "profiles: xem của mình hoặc admin" on public.profiles
  for select using (id = auth.uid() or public.is_admin());
create policy "profiles: sửa của mình hoặc admin" on public.profiles
  for update using (id = auth.uid() or public.is_admin())
  with check (id = auth.uid() or public.is_admin());
-- Từ website chỉ sửa được tên + sđt; đổi role (cấp quyền admin) chỉ làm trong SQL Editor
revoke update on public.profiles from anon, authenticated;
grant update (full_name, phone) on public.profiles to authenticated;

-- customers: khách xem hồ sơ của mình, admin toàn quyền
create policy "customers: xem của mình hoặc admin" on public.customers
  for select using (lower(email) = public.current_email() or public.is_admin());
create policy "customers: admin ghi" on public.customers
  for all using (public.is_admin()) with check (public.is_admin());

-- Dữ liệu công khai: ai cũng đọc được, chỉ admin sửa
