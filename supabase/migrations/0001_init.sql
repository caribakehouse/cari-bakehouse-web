-- Đơn mới: luôn "Chờ xử lý" và tạo hồ sơ khách theo email
create or replace function public.before_order_insert()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  if public.from_website() and not public.is_admin() then
    new.status := 'Chờ xử lý';
    new.created_at := public.today_vn();
    new.user_id := auth.uid();
  end if;
  perform public.ensure_customer(new.customer_name, new.customer_email, new.customer_phone, auth.uid());
  return new;
end;
$$;

create trigger orders_before_insert
  before insert on public.orders
  for each row execute function public.before_order_insert();

-- Đổi trạng thái đơn: chỉ Chờ xử lý → Đã giao / Đã hủy; Đã giao thì tự cộng điểm
create or replace function public.before_order_status_change()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  pts int;
begin
  if new.status is distinct from old.status then
    if old.status <> 'Chờ xử lý' then
      raise exception 'Đơn đã kết thúc, không thể đổi trạng thái';
    end if;

    pts := public.points_for_order(new.total);
    if new.status = 'Đã giao' and coalesce(new.customer_email, '') <> '' and pts > 0 then
      insert into public.point_logs (email, points, kind, order_id, title)
      values (new.customer_email, pts, 'order', new.id, 'Đơn hàng ' || new.id || ' hoàn tất')
      on conflict do nothing;
    end if;
  end if;
  return new;
end;
$$;

create trigger orders_status_change
  before update of status on public.orders
  for each row execute function public.before_order_status_change();

-- Yêu cầu đặt bánh mới: luôn "Mới", chưa có báo giá
create or replace function public.before_custom_request_insert()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  if public.from_website() and not public.is_admin() then
    new.status := 'Mới';
    new.quoted_price := null;
    new.created_at := public.today_vn();
